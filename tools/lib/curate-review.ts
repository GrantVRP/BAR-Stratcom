import { coverage, type SelectableCandidate } from './curate-select';
import type { UnmatchedSession } from '../import-fixtures';

export interface ReviewCandidate extends SelectableCandidate {
  title: string;
  faction: string;
  modeDetail: string;
  map: string;
  playedAt: string;
  replayUrl: string;
  opponents: string[];
  firstFactory: { unitId: string; name: string; sec: number } | null;
  sim: { energyStallSec: number; metalStallSec: number; flags: string[] } | null;
}

export const DECISION_TEMPLATE = 'DECISION: approve | reject — reason:';

const mmss = (sec: number): string => `${Math.floor(sec / 60)}:${String(Math.floor(sec % 60)).padStart(2, '0')}`;
const cap = (s: string): string => s.charAt(0).toUpperCase() + s.slice(1);

/** True when the sheet already holds review decisions (a DECISION line that is no longer the template). */
export function hasOwnerDecisions(markdown: string): boolean {
  return markdown.split(/\r?\n/).some((l) => l.trim().startsWith('DECISION:') && l.trim() !== DECISION_TEMPLATE);
}

export function renderReview(input: {
  generatedAt: string;
  games: number;
  teamsConsidered: number;
  candidates: readonly ReviewCandidate[];
  eligible: readonly SelectableCandidate[];
  unmatched: readonly UnmatchedSession[] | null;
}): string {
  const { candidates } = input;
  const out: string[] = [
    '# Curated candidates: review sheet',
    '',
    `Generated by \`tools/curate.ts\` on ${input.generatedAt.slice(0, 10)} from ${input.games} pro games ` +
      `(${input.teamsConsidered} human Armada/Cortex players, first 10 minutes each).`,
    '',
    `**How to review:** for each candidate, open the replay link if you want, then change its line \`${DECISION_TEMPLATE}\` ` +
      'to `DECISION: approve` or `DECISION: reject — reason: <why>`. Approved plans are published with tools/publish-curated.ts.',
    '',
    'Rules: at least 12 build steps and a factory before 3:00, 0 validation errors; picked round-robin over',
    'faction × opening × mode, highest player skill first, one plan per player. Sim numbers use the same model',
    'as the app (average wind of the map, default start).',
    '',
    '## Coverage',
    '',
    '| Faction / opening | 1v1 picked (eligible) | Team picked (eligible) |',
    '|---|---|---|'
  ];
  const cov = coverage(input.eligible, candidates);
  for (const faction of ['armada', 'cortex']) {
    for (const opening of ['bot', 'vehicle', 'air']) {
      const cell = (mode: string): string => {
        const c = cov.find((x) => x.cell === `${faction}/${opening}/${mode}`)!;
        return `${c.picked} (${c.available})`;
      };
      out.push(`| ${cap(faction)} ${opening} | ${cell('1v1')} | ${cell('team')} |`);
    }
  }
  const empty = cov.filter((c) => c.available === 0).map((c) => c.cell.replace(/\//g, ' '));
  out.push('');
  out.push(
    empty.length > 0
      ? `**Gaps:** no eligible opening for ${empty.join(', ')} in these games; more pro captures are needed to fill ${empty.length === 1 ? 'it' : 'them'}.`
      : '**Gaps:** none.'
  );
  out.push('', `## Candidates (${candidates.length})`, '');

  candidates.forEach((c, i) => {
    const ff = c.firstFactory ? `first factory ${c.firstFactory.name} (\`${c.firstFactory.unitId}\`) at ${mmss(c.firstFactory.sec)}` : 'no factory';
    const sim = c.sim
      ? `energy stall ${Math.round(c.sim.energyStallSec)} s · metal stall ${Math.round(c.sim.metalStallSec)} s` +
        (c.sim.flags.length > 0 ? ` (${c.sim.flags.join(', ')})` : '')
      : 'simulation failed';
    out.push(
      `### ${i + 1}. ${c.title}`,
      '',
      `- Plan: \`${c.key}\` · ${cap(c.faction)} · ${c.modeDetail}`,
      `- Player: ${c.player} (skill ${c.skill.toFixed(1)}) vs ${c.opponents.join(', ')} on ${c.map}, played ${c.playedAt}`,
      `- Replay: ${c.replayUrl}`,
      `- ${c.steps} steps · ${ff}`,
      `- Sim on ${c.map}: ${sim}`,
      '',
      DECISION_TEMPLATE,
      ''
    );
  });

  out.push('## Unmatched sessions', '');
  if (input.unmatched === null) {
    out.push('Raw pro recordings are not on this machine, so unmatched sessions could not be listed.');
  } else if (input.unmatched.length === 0) {
    out.push('None: every H2 recording matched a replay in `h2-replay-list.json`.');
  } else {
    out.push('Recorded during H2 but not in `h2-replay-list.json`; not imported and not curated:', '');
    for (const u of input.unmatched) out.push(`- \`${u.sessionId}\` · ${u.map} · ${u.players.join(' vs ')}`);
  }
  out.push('');
  return out.join('\n');
}
