function cell(text: string): string {
  return text.replace(/\|/g, '\\|');
}

function fence(text: string): string {
  const longest = Math.max(2, ...[...text.matchAll(/`+/g)].map((m) => m[0].length));
  const ticks = '`'.repeat(longest + 1);
  return `${ticks}text\n${text}\n${ticks}`;
}

export function renderNotices(shipped: ShippedPackage[], electronVersion: string): string {
  const groups = new Map<string, ShippedPackage[]>();
  for (const p of shipped) if (p.text) groups.set(p.text, [...(groups.get(p.text) ?? []), p]);

  const lines = [
    '# Third-party notices',
    '',
    'BAR StratCom is MIT-licensed (`LICENSE`). Its in-game widget, `gui_stratcom.lua`, is GPL-2.0-or-later',
    '(`widget/LICENSE` in the source, `resources/licenses/gui_stratcom-GPL-2.0.txt` in the release).',
    'This file lists what the release contains from others.',
    '',
    '<!-- Generated by tools/third-party-notices.ts from the app\'s runtime imports and package-lock.json.',
    '     Do not edit by hand; `npm run verify` fails while it is out of date. -->',
    '',
    '## Electron and Chromium',
    '',
    `The app runs on Electron ${electronVersion} (MIT), which contains Chromium and Node.js. Their licences ship`,
    'beside `BAR StratCom.exe` as `LICENSE.electron.txt` and `LICENSES.chromium.html`.',
    '',
    '## Beyond All Reason',
    '',
    BAR_CREDITS,
    '',
    '## Packages',
    '',
    `${shipped.length} npm packages are bundled into the app or ship in its \`node_modules\`. The three fonts`,
    '(Press Start 2P, VT323, JetBrains Mono, SIL Open Font License 1.1) come from the `@fontsource`',
    'packages; their licences also ship in `resources/licenses/`.',
    '',
    '| Package | Version | Licence |',
    '| --- | --- | --- |',
    ...shipped.map((p) => `| ${cell(p.name)} | ${p.version} | ${cell(p.license)}${p.text ? '' : ' (the package has no licence file)'} |`),
    '',
    '## Licence texts',
    ''
  ];
  for (const [text, packages] of groups) {
    const names = packages.map((p) => `${p.name} ${p.version}`).join(', ');
    lines.push(`### ${packages[0]!.license}: ${names}`, '', fence(text), '');
  }
  return `${lines.join('\n').trimEnd()}\n`;
}

function main(): void {
  const lock = JSON.parse(fs.readFileSync(path.join(ROOT, 'package-lock.json'), 'utf-8')) as { packages: LockPackages };
  const shipped = readShipped(ROOT, lock.packages, closure(lock.packages, shippedRoots(ROOT)));
  const electron = JSON.parse(fs.readFileSync(path.join(ROOT, 'node_modules/electron/package.json'), 'utf-8')) as { version: string };
  const text = renderNotices(shipped, electron.version);

  if (process.argv.includes('--check')) {
    const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf-8').replace(/\r\n/g, '\n') : '';
    if (current !== text) {
      console.error('THIRD_PARTY_NOTICES.md is out of date: run npx tsx tools/third-party-notices.ts');
      process.exitCode = 1;
      return;
    }
    console.log(`THIRD_PARTY_NOTICES.md is up to date (${shipped.length} packages).`);
    return;
  }
  fs.writeFileSync(OUT, text);
  console.log(`Wrote THIRD_PARTY_NOTICES.md (${shipped.length} packages, ${text.length} bytes).`);
}

main();
